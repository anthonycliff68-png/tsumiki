#!/usr/bin/env bash
#
# Regenerate the screenshot board.
#
# Every screen is reached by its own deep link rather than by tapping, so this
# does not break when a button moves — there is nothing to find. The app is
# terminated before each one, because iOS asks "Open in Tsumiki?" when a URL
# arrives for an app that is already frontmost, and a prompt is a tap, and a
# tap is the thing we are trying not to depend on.
#
# What it cannot do: set up state. A screen that needs a crew, or a trial that
# has run out, needs that to be true in the database first. docs/screens.md
# records what each screen needs under "Needs".
#
# Screens that live at an id — a crew, one habit — need that id, and an id
# belongs to whoever's data this is. So they come from scripts/shots.env, which
# is not committed. To find a crew's:
#
#   select id, name from crews;
#   select h.id, h.name, count(c.id) as checkins from habits h
#     left join checkins c on c.habit_id = h.id where h.archived_at is null
#     group by h.id, h.name order by checkins desc;
#
# For the habit, pick one with history — the screen is a weekday breakdown and
# an empty one shows nothing worth looking at.
#
# Usage:  scripts/shots.sh [device-name-or-udid]
set -euo pipefail

# Not committed: holds the ids that are specific to one person's data.
[ -f scripts/shots.env ] && . scripts/shots.env

DEVICE="${1:-iPhone 17 Pro Max}"
BUNDLE="com.tsumiki.app"
OUT="docs/screenshots"
SETTLE="${SETTLE:-6}"   # seconds to let a screen finish animating

# path|filename|what it is
SCREENS=(
  "/|01-today|Today — the day as a hand of cards"
  "/my-day|02-my-day|My Day — the same habits on an hour grid"
  "/crews|03-crews|Crews — every crew and its shared streak"
  "/progress|04-progress|Progress — opens on Overall"
  "/you|05-you|You — profile, subscription, notifications"
  "/plans|06-plans|Plans — the paywall, opened on purpose"
  "/new-habit|07-new-habit|New habit — name, when, days, colour, solo or crew"
  "/schedule|08-schedule|Schedule — the moments of your day"
  "/account|11-account|Account — change your email or your password (1.2)"
  "/feedback|12-feedback|Feedback — write in without leaving the app (1.2)"
)

# Needs a real crew, so it is only captured when one is named.
if [ -n "${CREW_ID:-}" ]; then
  SCREENS+=("/crew/${CREW_ID}|09-crew|A crew — shared streak, the week behind it, who is in today")
else
  echo "  (no CREW_ID in scripts/shots.env — skipping the crew screen)"
fi

# Needs a habit with some history behind it.
if [ -n "${HABIT_ID:-}" ]; then
  SCREENS+=("/habit/${HABIT_ID}|10-habit|One habit — its history, and which weekday keeps breaking it")
else
  echo "  (no HABIT_ID in scripts/shots.env — skipping the habit screen)"
fi

mkdir -p "$OUT"
SHA="$(git rev-parse --short HEAD)"
DIRTY=""
git diff --quiet || DIRTY=" (uncommitted changes)"

echo "Capturing against ${SHA}${DIRTY} on ${DEVICE}"

for row in "${SCREENS[@]}"; do
  IFS='|' read -r path name _desc <<< "$row"
  xcrun simctl terminate "$DEVICE" "$BUNDLE" >/dev/null 2>&1 || true
  sleep 1
  xcrun simctl openurl "$DEVICE" "tsumiki://${path}" >/dev/null
  sleep "$SETTLE"
  xcrun simctl io "$DEVICE" screenshot "$OUT/${name}.png" >/dev/null
  echo "  $name"
done

# A board that quietly shows an old screen is worse than no board, so each run
# records what it was taken against.
{
  echo "# Screenshot board"
  echo
  echo "Regenerated by \`scripts/shots.sh\`. Do not edit by hand."
  echo
  echo "| | Screen | What it is |"
  echo "|---|---|---|"
  for row in "${SCREENS[@]}"; do
    IFS='|' read -r _path name desc <<< "$row"
    echo "| <img src=\"${name}.png\" width=\"150\"> | **${name#*-}** | ${desc} |"
  done
  echo
  echo "---"
  echo
  echo "Taken: $(date '+%-d %B %Y, %H:%M %Z')"
  echo "Commit: \`${SHA}\`${DIRTY}"
  echo
  MISSING=""
  [ -z "${CREW_ID:-}" ]  && MISSING="${MISSING}CREW_ID "
  [ -z "${HABIT_ID:-}" ] && MISSING="${MISSING}HABIT_ID "
  if [ -n "$MISSING" ]; then
    echo "Screens missing from this run for want of an id: \`${MISSING% }\`."
    echo "Set them in \`scripts/shots.env\`; the header of"
    echo "\`scripts/shots.sh\` has the queries."
    echo
  fi
  echo "Screens needing state this script cannot create — an expired trial, a"
  echo "nudge, the paywall as a wall — are listed in [screens.md](../screens.md)"
  echo "under **Needs**, and are still captured by hand."
} > "$OUT/README.md"

echo "Board written to $OUT/README.md"
